/**
 * Automatically generates and recalculates the full authentic SWELECT 145-activity
 * schedule aligned to any custom project start date and working calendar using the CPM Engine.
 */
export function generateProjectActivitiesForTimeline(
  startDateStr: string,
  calendar: WorkingCalendar = DEFAULT_WORKING_CALENDAR,
  resetProgress: boolean = false,
  capacityMWp?: number,
  areaAcres?: number
): {
  activities: Activity[];
  forecastCompletionDate: string;
  projectDurationDays: number;
  criticalPathCount: number;
} {
  const cap = capacityMWp ? Number(capacityMWp) : undefined;
  const area = areaAcres ? Number(areaAcres) : undefined;

  const initialActivities: Activity[] = SWELECT_RAW_ACTIVITIES.map(a => {
    let totalQty = a.totalPlannedQuantity;
    let completedQty = a.completedQuantity;
    let remainingQty = a.remainingQuantity;

    if (a.quantityUnit === 'MWp' && cap) {
      totalQty = cap;
      completedQty = resetProgress ? 0 : Math.round(cap * 0.1 * 10) / 10;
      remainingQty = resetProgress ? cap : Math.max(0, cap - (completedQty || 0));
    } else if (a.quantityUnit === 'Acres' && area) {
      totalQty = area;
      completedQty = resetProgress ? 0 : area;
      remainingQty = resetProgress ? area : 0;
    }

    return {
      ...a,
      totalPlannedQuantity: totalQty,
      completedQuantity: resetProgress ? 0 : completedQty,
      remainingQuantity: resetProgress ? totalQty : remainingQty,
      earlyStart: startDateStr,
      earlyFinish: startDateStr,
      lateStart: startDateStr,
      lateFinish: startDateStr,
      totalFloat: 0,
      freeFloat: 0,
      isCritical: false,
      ...(resetProgress
        ? {
            status: 'NOT_STARTED' as const,
            progressPercent: 0,
            actualStart: undefined,
            actualFinish: undefined,
            actualDuration: undefined,
            completedQuantity: 0,
            remainingQuantity: totalQty
          }
        : {})
    };
  });

  const cpmResult = calculateSchedule(initialActivities, startDateStr, calendar);

  // Synchronize baseline and currentPlanned dates with calculated early dates
  const alignedActivities = cpmResult.activities.map(act => ({
    ...act,
    baselineStart: act.earlyStart,
    baselineFinish: act.earlyFinish,
    currentPlannedStart: act.earlyStart,
    currentPlannedFinish: act.earlyFinish
  }));

  const criticalCount = alignedActivities.filter(a => a.isCritical).length;
  const durationDays = countWorkingDaysBetween(startDateStr, cpmResult.forecastCompletionDate, calendar);

  return {
    activities: alignedActivities,
    forecastCompletionDate: cpmResult.forecastCompletionDate,
    projectDurationDays: durationDays,
    criticalPathCount: criticalCount
  };
}

